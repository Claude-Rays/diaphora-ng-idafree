import os
import sys

# license notice written at the top of the generated file
LICENSE_NOTICE = __doc__.strip().split("\n\n")[0:4]

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

def cpp_raw(s):
  # Raw string literal, MSVC limits a single literal to ~16KB so split it
  delim = "SQL"
  assert (")" + delim + '"') not in s
  chunks = [s[i:i + 8000] for i in range(0, len(s), 8000)] or [""]
  return "\n".join(f'R"{delim}({c}){delim}"' for c in chunks)

def main():
  src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "..", "diaphora")
  sys.path.insert(0, os.path.abspath(src))
  import diaphora_heuristics as h

  flag_names = {
    h.HEUR_FLAG_UNRELIABLE: "HEUR_FLAG_UNRELIABLE",
    h.HEUR_FLAG_SLOW: "HEUR_FLAG_SLOW",
    h.HEUR_FLAG_SAME_CPU: "HEUR_FLAG_SAME_CPU",
  }
  ratio_names = {
    h.HEUR_TYPE_NO_FPS: "HEUR_TYPE_NO_FPS",
    h.HEUR_TYPE_RATIO: "HEUR_TYPE_RATIO",
    h.HEUR_TYPE_RATIO_MAX: "HEUR_TYPE_RATIO_MAX",
    h.HEUR_TYPE_RATIO_MAX_TRUSTED: "HEUR_TYPE_RATIO_MAX_TRUSTED",
  }

  out = []
  out.extend(("// " + l).rstrip() for l in "\n\n".join(LICENSE_NOTICE).split("\n"))
  out.append("")
  out.append("// Generated by tools/gen_heuristics.py from diaphora_heuristics.py. Do not edit.")
  out.append("// clang-format off")
  out.append("")
  out.append("static const char SELECT_FIELDS_TEMPLATE[] =")
  out.append(cpp_raw(h.SELECT_FIELDS) + ";")
  out.append("")
  out.append("static const heuristic_t HEURISTICS_DATA[] =")
  out.append("{")
  for heur in h.HEURISTICS:
    flags = " | ".join(f"(1u << {flag_names[f]})" for f in heur["flags"]) or "0"
    min_value = heur.get("min", 0.0)
    out.append("  {")
    out.append(f"    {cpp_raw(heur['name'])},")
    out.append(f"    {cpp_raw(heur['category'])},")
    out.append(f"    {ratio_names[heur['ratio']]},")
    out.append(f"    {float(min_value)!r},")
    out.append(f"    {flags},")
    out.append(f"    {cpp_raw(heur['sql'])}")
    out.append("  },")
  out.append("};")
  out.append("")

  dest = os.path.join(ROOT, "src", "heuristics_data.inc")
  with open(dest, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out))
  print(f"Wrote {len(h.HEURISTICS)} heuristics to {dest}")

if __name__ == "__main__":
  main()
